#!/usr/bin/env python3
"""docs-pattern v2 compiler — docs/ pages -> generated index, current status, full compile, backlinks.

Source pages (written by workers, never by the generator):
  docs/state/S###.md               one page per stage; exactly one has `status: active`
  docs/issues/I###.md              one page per issue (I### = GitHub #### when a tracker exists)
  docs/rules/R###.md               one working rule per page (how to work on this project, with why);
                                   scripts/rules_hook.py injects them into Claude's context
  docs/documentation/**.md         concept pages; `a/b.md` is a child of `a.md`
  docs/history/<same path>.md      one per page: `- YYYY-MM-DD what — why` bullets, oldest first
Every page starts with frontmatter `title:` (+ `status:` for state/issues).
Links: [[ID]], [[ID|text]], [[ID#heading]]. IDs: S###, I###, R###, documentation path without .md.

Generated (never edit by hand): docs/index.md, docs/current_status.md,
docs/_build/compiled.md, docs/_build/backlinks.json.

Usage: docs_build.py [DOCS_DIR] [--check] [--selftest]
  (default)  validate + write generated files; exit 1 on FAIL
  --check    validate + verify generated files are up to date; writes nothing
  --selftest prove every FAIL rule fires and the build is deterministic
"""
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

LINK = re.compile(r"(?<!!)\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]")
DATED = re.compile(r"^- (\d{4}-\d{2}-\d{2}) \S")
STATUSES = {"state": {"active", "done"}, "issues": {"open", "closed", "onhold"}}
PREFIX = {"state": "S", "issues": "I", "rules": "R"}
MARK = "<!-- generated by docs_build.py from docs/ pages; do not edit -->"
STATE_HEADINGS = ("목표", "완료 조건", "지금 상태", "다음 한 걸음")   # Agent State 양식(templates/state.md), "결정과 막힌 것" 은 선택
STATE_MAX = 2500   # 진행 중 단계 본문 글자 수. 경과는 history/state/S###.md 로
JOURNAL = re.compile(r"^(?!\s*(?:[-*]|\d+\.)\s)\**\s*\d{4}-\d{2}-\d{2}[^\n]*(추가|갱신|:)", re.M)
RULE_LABELS = {"feedback": ("목적", "언제", "절차", "Why"), "reference": ("무엇",)}   # = memory_build.TYPES 의 SOP·사실 틀
ROOT = "overview"   # Document 의 뿌리: 본문 전체가 context 에 들어가고, 나머지 문서는 summary 한 줄씩
CONTEXT_LIMIT = 9000  # context() 합계 글자 수. Claude Code 는 hook 출력 문자열이 10,000자를 넘으면 파일로 빼고 앞 2,000자만 넣는다


def frontmatter(text):
    if not text.startswith("---\n"):
        return {}, text
    head, _, body = text[4:].partition("\n---\n")
    fm = {}
    for line in head.splitlines():
        key, sep, val = line.partition(":")
        if sep:
            val = val.strip()
            if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":  # YAML 따옴표 (제목에 ':' 가 있으면 필요)
                val = val[1:-1]
            fm[key.strip()] = val
    return fm, body.strip("\n")


def load(docs):
    """-> pages {id: dict}, fails [str]"""
    pages, fails = {}, []

    def add(pid, kind, path):
        fm, body = frontmatter(path.read_text(encoding="utf-8"))
        rel = path.relative_to(docs).as_posix()
        if pid in pages:
            fails.append(f"ID 중복: {pid} ({pages[pid]['rel']}, {rel})")
            return
        if not fm.get("title"):
            fails.append(f"{rel}: frontmatter title 없음")
        if kind in STATUSES and fm.get("status") not in STATUSES[kind]:
            fails.append(f"{rel}: status 는 {sorted(STATUSES[kind])} 중 하나 (지금 {fm.get('status')!r})")
        pages[pid] = {"id": pid, "kind": kind, "rel": rel, "title": fm.get("title", pid),
                      "status": fm.get("status", ""), "body": body, "fm": fm}

    for kind in ("state", "issues", "rules"):
        for f in sorted((docs / kind).glob("*.md")):
            if re.fullmatch(rf"{PREFIX[kind]}\d{{3}}", f.stem):
                add(f.stem, kind, f)
            elif not (kind == "rules" and f.name == "_ltm.md"):   # _ltm.md = 메모를 고르는 질의, 페이지 아님
                fails.append(f"{f.relative_to(docs).as_posix()}: 파일 이름은 {PREFIX[kind]}NNN.md")
    for f in sorted((docs / "documentation").rglob("*.md")):
        add(f.relative_to(docs / "documentation").with_suffix("").as_posix(), "doc", f)
    return pages, fails


def routine(pages):
    """루틴(끝 없는 반복 루프) = overview frontmatter `kind: routine`. 단계(state/) 대신 `now:` 스크립트가
    데이터에서 current_status.md 를 만든다. -> now 스크립트 경로(repo 기준) 또는 None"""
    fm = pages.get("overview", {}).get("fm", {})
    return fm.get("now", "") if fm.get("kind") == "routine" else None


def validate(docs, pages):
    fails, warns = [], []
    states = [p for p in pages.values() if p["kind"] == "state"]
    active = [p["id"] for p in states if p["status"] == "active"]
    now = routine(pages)
    if now is not None:
        if states:
            fails.append("루틴(kind: routine)은 state/ 단계를 쓰지 않음 — 현재 상태는 now 스크립트가 데이터에서 만든다")
        if not now:
            fails.append("documentation/overview.md: 루틴은 frontmatter now: <current_status.md 를 만드는 스크립트> 필요")
    elif len(active) != 1:
        fails.append(f"status: active 인 단계가 정확히 1개여야 함 (지금 {active or '없음'})")
    for p in pages.values():
        if p["kind"] == "doc" and "/" in p["id"]:
            parent = p["id"].rsplit("/", 1)[0]
            if parent not in pages:
                fails.append(f"{p['rel']}: 부모 문서 documentation/{parent}.md 없음")

    links = {}  # source id -> sorted target ids (page body + its history)
    history_rels = set()
    for p in pages.values():
        text = p["body"]
        h = docs / "history" / p["rel"]
        history_rels.add(("history/" + p["rel"]))
        if not h.exists():
            fails.append(f"{p['rel']}: 이력 파일 history/{p['rel']} 없음")
            p["history"] = ""
        else:
            p["history"] = h.read_text(encoding="utf-8").strip("\n")
            text += "\n" + p["history"]
            prev = ""
            for line in p["history"].splitlines():
                if not line.startswith("- "):
                    continue
                m = DATED.match(line)
                if not m:
                    fails.append(f"history/{p['rel']}: 날짜로 시작하지 않는 항목: {line[:40]}")
                elif m.group(1) < prev:
                    fails.append(f"history/{p['rel']}: 날짜 역순 ({m.group(1)} < {prev})")
                else:
                    prev = m.group(1)
        targets = sorted({t.strip() for t in LINK.findall(text)})
        for t in targets:
            if t not in pages:
                fails.append(f"{p['rel']}: 깨진 링크 [[{t}]]")
        links[p["id"]] = [t for t in targets if t in pages and t != p["id"]]
    for h in sorted((docs / "history").rglob("*.md")):
        rel = h.relative_to(docs).as_posix()
        if rel not in history_rels:
            fails.append(f"{rel}: 대응하는 페이지 없음")

    back = {pid: [] for pid in pages}
    for src, targets in links.items():
        for t in targets:
            back[t].append(src)
    for pid, srcs in back.items():
        if pages[pid]["kind"] == "issues" and not srcs:
            warns.append(f"{pages[pid]['rel']}: 어느 페이지도 링크하지 않는 이슈")
    for p in pages.values():   # Agent State = 진행 중 단계 page, 양식 = templates/state.md
        if p["kind"] == "state" and p["status"] == "active":
            miss = [h for h in STATE_HEADINGS if not re.search(rf"^## {h}\s*$", p["body"], re.M)]
            if miss:
                warns.append(f"{p['rel']}: Agent State 양식의 소제목 없음 — " + ", ".join(f"## {h}" for h in miss))
            if len(p["body"]) > STATE_MAX:
                warns.append(f"{p['rel']}: Agent State 본문 {len(p['body']):,}자 > {STATE_MAX:,} — 경과는 history, 사실은 Document, 열린 일은 이슈로")
            if JOURNAL.search(p["body"]):
                warns.append(f"{p['rel']}: 날짜 경과 문단 — history/{p['rel']} 로")
    for p in pages.values():   # Short Term Memory 도 Long Term Memory 와 같은 틀 (templates/memory/)
        if p["kind"] == "rules":
            t = p["fm"].get("type")
            if t not in RULE_LABELS:
                warns.append(f"{p['rel']}: type 은 {sorted(RULE_LABELS)} 중 하나 (feedback = SOP 틀, reference = 사실 틀)")
            else:
                miss = [h for h in RULE_LABELS[t] if f"**{h}" not in p["body"]]
                if miss:
                    warns.append(f"{p['rel']}: {t} 틀의 소제목 없음 — " + ", ".join(f"**{h}:**" for h in miss))
    inbox = docs / "_inbox"
    if inbox.is_dir() and any(inbox.iterdir()):
        warns.append("_inbox/ 에 처리하지 않은 변경 요청이 있음")
    return fails, warns, {k: sorted(v) for k, v in back.items()}


def doc_order(pages):
    return sorted((p for p in pages.values() if p["kind"] == "doc"), key=lambda p: p["id"].split("/"))


def demote(body, by):
    out, fence = [], False
    for line in body.splitlines():
        if line.startswith("```"):
            fence = not fence
        out.append("#" * by + line if (not fence and line.startswith("#")) else line)
    return "\n".join(out)


def render(pages, back, now=None):
    by_kind = lambda k: sorted((p for p in pages.values() if p["kind"] == k), key=lambda p: p["id"])
    states, issues, rules, docs_ = by_kind("state"), by_kind("issues"), by_kind("rules"), doc_order(pages)
    active = next((p for p in states if p["status"] == "active"), None)
    link = lambda p: f"[[{p['id']}]] {p['title']}"

    idx = [MARK, "# Docs index", ""]
    if active:
        idx += ["## 현재 단계", "", link(active), ""]
    if now:
        idx += ["## 지금", "", f"루틴 — current_status.md 는 `{now}` 가 데이터에서 만든다.", ""]
    if rules:
        idx += ["## 규칙", ""] + [f"- {link(p)}" for p in rules] + [""]
    idx += ["## 문서", ""]
    idx += [f"{'  ' * p['id'].count('/')}- {link(p)}" for p in docs_] or ["(없음)"]
    idx += ["", "## 이슈", "", "| ID | 제목 | 상태 |", "|---|---|---|"]
    idx += [f"| [[{p['id']}]] | {p['title']} | {p['status']} |" for p in issues]
    if states:
        idx += ["", "## 단계", "", "| ID | 제목 | 상태 |", "|---|---|---|"]
        idx += [f"| [[{p['id']}]] | {p['title']} | {p['status']} |" for p in states]
    idx += ["", "## 백링크", "", "| 페이지 | 링크한 곳 |", "|---|---|"]
    idx += [f"| [[{pid}]] | {', '.join(f'[[{s}]]' for s in srcs)} |" for pid, srcs in sorted(back.items()) if srcs]

    cur = [MARK, f"# 현재 단계: [[{active['id']}]] {active['title']}", "", active["body"], "",
           "전체 문서 목록 = docs/index.md"] if active else [MARK, "# 현재 단계 없음"]

    comp = [MARK, "# Compiled docs", ""]
    order = ([active] if active else []) + rules + docs_ + issues + [p for p in states if p is not active]
    for p in order:
        depth = 2 + (p["id"].count("/") if p["kind"] == "doc" else 0)
        comp += [f"{'#' * depth} [[{p['id']}]] {p['title']}" + (f" ({p['status']})" if p["status"] else ""), "",
                 demote(p["body"], depth), ""]
        if back[p["id"]]:
            comp += ["링크한 곳: " + ", ".join(f"[[{s}]]" for s in back[p["id"]]), ""]
        if p.get("history"):
            comp += [f"{'#' * (depth + 1)} 이력", "", p["history"], ""]

    out = {"index.md": idx, "_build/compiled.md": comp, **({} if now else {"current_status.md": cur})}
    out = {k: "\n".join(v).rstrip("\n") + "\n" for k, v in out.items()}
    out["_build/backlinks.json"] = json.dumps(back, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    return out


def context(docs, pages):
    """What rules_hook puts into the agent's context -> {part: text}. Archive (state/, issues/) is read on demand.
    Agent State = current_status.md · Short Term Memory = rules/ · Document = the root page (documentation/overview.md)
    in full, then every other documentation page as one line `[[id]] title — summary`, indented by depth."""
    cs = docs / "current_status.md"
    state = cs.read_text(encoding="utf-8").replace(MARK, "").strip() if cs.exists() else ""
    stm = [f"## {p['id']} {p['title']}\n{p['body']}" for p in sorted(pages.values(), key=lambda p: p["id"])
           if p["kind"] == "rules"]
    root = pages.get(ROOT)
    tree = ["  " * p["id"].count("/") + f"- [[{p['id']}]] {p['title']}" + (f" — {p['fm']['summary']}" if p["fm"].get("summary") else "")
            for p in doc_order(pages) if p["id"] != ROOT]
    doc = ([f"## {root['title']} ([[{ROOT}]])\n{demote(root['body'], 1)}"] if root else []) + (["\n".join(tree)] if tree else [])
    from memory_build import HUB_ORG, select   # 조직·프로젝트 rules/_ltm.md 가 태그로 고른 Long Term Memory 메모
    ltm = {n: t for q in (docs.parent / "rules/_ltm.md", docs / "rules/_ltm.md") if q.exists()
           for n, t in select(q, HUB_ORG.get(docs.parent.name))}
    return {"Agent State": state, "Short Term Memory": "\n\n".join(stm), "Document": "\n\n".join(doc),
            "Long Term Memory": "\n".join(f"- {n}: {t}" for n, t in ltm.items())}


def run(docs, check=False, quiet=False):
    """-> (fails, warns). Writes generated files unless check."""
    pages, fails = load(docs)
    f2, warns, back = validate(docs, pages)
    fails += f2
    now = routine(pages)
    out = render(pages, back, now)
    if now:  # 루틴: current_status.md 는 now 스크립트의 생성물, 최신 판정도 그 스크립트가 한다
        r = subprocess.run([sys.executable, str(docs.parent / now)] + (["--check"] if check else []),
                           cwd=docs.parent, capture_output=True, text=True)
        if r.returncode:
            fails.append(f"now 스크립트 {now} 실패: {(r.stdout + r.stderr).strip()[-200:]}")
    for name, text in out.items():
        path = docs / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                fails.append(f"{name}: 생성물이 최신이 아님 (docs_build.py 실행 필요)")
        elif not fails:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    ctx = context(docs, pages)
    if sum(map(len, ctx.values())) > CONTEXT_LIMIT:
        parts = " · ".join(f"{k} {len(v):,}" for k, v in ctx.items())
        warns.append(f"context 합계가 상한 {CONTEXT_LIMIT:,}자를 넘음 ({parts}) — 뿌리 문서를 줄이고 세부는 하위 문서·state/·issues/ 로")
    for p in doc_order(pages):
        if p["id"] != ROOT and not p["fm"].get("summary"):
            warns.append(f"{p['rel']}: frontmatter summary 없음 (Document 나무의 한 줄, 120자 이하)")
        elif len(p["fm"].get("summary", "")) > 120:
            warns.append(f"{p['rel']}: summary 가 120자를 넘음")
    if not quiet:
        for m in fails:
            print("FAIL", m)
        for m in warns:
            print("WARN", m)
        print(f"{len(fails)} FAIL, {len(warns)} WARN, 페이지 {len(pages)}")
    return fails, warns


def selftest():
    def w(root, rel, text):
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text, encoding="utf-8")

    def fixture(root):
        w(root, "state/S001.md", "---\ntitle: 이관\nstatus: done\n---\n기사 이관.")
        w(root, "state/S002.md", "---\ntitle: 301\nstatus: active\n---\n## 목표\n[[I001]] 해결, [[arch/redirect|리다이렉트]].\n\n"
                                 "## 완료 조건\n- [ ] 301\n\n## 지금 상태\n- 진행 중: 규칙 작성\n\n## 다음 한 걸음\n규칙 시험")
        w(root, "issues/I001.md", "---\ntitle: \"구 URL: 301\"\nstatus: open\n---\n설계 [[arch#개요]].")
        w(root, "documentation/arch.md", "---\ntitle: 구조\nsummary: 구조 한 줄\n---\n# 개요\n```\n# 코드\n```")
        w(root, "documentation/arch/redirect.md", "---\ntitle: 리다이렉트\nsummary: 옛 주소를 새 주소로\n---\n[[S002]] 에서 만듦.")
        w(root, "rules/R001.md", "---\ntitle: 산출은 전부 저장\ntype: feedback\n---\n**목적:** 버리지 않는다.\n**언제:** 실행 뒤\n**절차:**\n1. 저장 → 확인\n**Why:** 잃은 적 있음")
        for rel in ("state/S001.md", "state/S002.md", "issues/I001.md", "documentation/arch.md",
                    "documentation/arch/redirect.md", "rules/R001.md"):
            w(root, "history/" + rel, "- 2026-09-01 만듦 — 시작\n- 2026-09-02 고침 — [[S002]]")

    mutations = [
        ("깨진 링크", lambda r: w(r, "issues/I001.md", "---\ntitle: x\nstatus: open\n---\n[[I999]]")),
        ("ID 중복", lambda r: w(r, "documentation/S001.md", "---\ntitle: x\n---\n")),
        ("이력 파일", lambda r: (r / "history/issues/I001.md").unlink()),
        ("날짜로 시작하지", lambda r: w(r, "history/issues/I001.md", "- 어제 고침")),
        ("날짜 역순", lambda r: w(r, "history/issues/I001.md", "- 2026-09-05 a\n- 2026-09-01 b")),
        ("대응하는 페이지 없음", lambda r: w(r, "history/issues/I002.md", "- 2026-09-01 a")),
        ("정확히 1개", lambda r: w(r, "state/S001.md", "---\ntitle: x\nstatus: active\n---\n")),
        ("부모 문서", lambda r: w(r, "documentation/ops/deploy.md", "---\ntitle: x\n---\n")),
        ("status 는", lambda r: w(r, "issues/I001.md", "---\ntitle: x\nstatus: 해결\n---\n[[S002]]")),
        ("title 없음", lambda r: w(r, "documentation/arch.md", "---\n---\n")),
        ("파일 이름은", lambda r: w(r, "issues/I001-slug.md", "---\ntitle: x\nstatus: open\n---\n")),
        ("파일 이름은 RNNN", lambda r: w(r, "rules/save-all.md", "---\ntitle: x\n---\n")),
        ("rules/R001.md: frontmatter title", lambda r: w(r, "rules/R001.md", "---\n---\n")),
    ]
    with tempfile.TemporaryDirectory() as tmp:
        base = Path(tmp) / "base"
        fixture(base)
        fails, warns = run(base, quiet=True)
        assert not fails and not warns, (fails, warns)
        first = {p: (base / p).read_text() for p in ("index.md", "current_status.md", "_build/compiled.md")}
        assert not run(base, check=True, quiet=True)[0], "생성 직후 --check 가 실패함"
        run(base, quiet=True)
        assert first == {p: (base / p).read_text() for p in first}, "두 번 빌드 결과가 다름"
        assert "# 코드" in first["_build/compiled.md"], "코드 블록 안 # 를 제목으로 강등함"
        assert json.loads((base / "_build/backlinks.json").read_text())["I001"] == ["S002"]
        assert "| 구 URL: 301 |" in (base / "index.md").read_text(), "YAML 따옴표 제목을 벗기지 않음"
        assert "## 규칙\n\n- [[R001]] 산출은 전부 저장" in first_index if (first_index := (base / "index.md").read_text()) else 0, "규칙 목록 없음"
        for i, (needle, mutate) in enumerate(mutations):
            root = Path(tmp) / f"m{i}"
            shutil.copytree(base, root)
            mutate(root)
            fails, _ = run(root, quiet=True)
            assert any(needle in f for f in fails), f"{needle!r} 가 잡히지 않음: {fails}"
        stale = Path(tmp) / "stale"
        shutil.copytree(base, stale)
        w(stale, "documentation/arch.md", "---\ntitle: 바뀐 구조\n---\n본문")
        assert any("최신이 아님" in f for f in run(stale, check=True, quiet=True)[0]), "stale 생성물 미검출"
        rt = Path(tmp) / "routine"
        w(rt, "docs/documentation/overview.md", "---\ntitle: 루프\nkind: routine\nnow: tools/now.py\n---\n[[I001]]")
        w(rt, "docs/issues/I001.md", "---\ntitle: 정할 것\nstatus: open\n---\n")
        for rel in ("documentation/overview.md", "issues/I001.md"):
            w(rt, "docs/history/" + rel, "- 2026-09-01 만듦 — x")
