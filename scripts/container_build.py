#!/usr/bin/env python3
"""컨테이너(여러 프로젝트가 든 폴더)의 프로젝트 목록을 파일 시스템에서 결정론적으로 만든다.

- 프로젝트 = 하위 폴더 중 `.git` 또는 `docs/` 가 있는 것.
- 컨테이너 = `PROJECTS.md` 가 있는 폴더. 처음 `container_build.py <폴더>` 를 한 번 실행하는 것이 "여기는 컨테이너" 선언이다
  (폴더 모양으로 추측하지 않는다: 하위에 repo 가 있는 프로젝트도, 프로젝트가 두 단계 아래에 있는 컨테이너도 있다).
  안쪽 컨테이너는 위 목록에서 링크되고, 위를 빌드하면 함께 다시 빌드된다.
- 사람이 쓰는 파일은 `LEGACY.md` 하나: `- <이름> — <remote> — <YYYY-MM-DD>` (보관한 프로젝트, 로컬에서 지워도 목록에 남는다).
- 산출 `PROJECTS.md` 는 생성물. `--check` 는 내용이 최신이 아니거나 LEGACY.md 형식이 틀리면 exit 1.

Usage: container_build.py CONTAINER [--check]   |   --selftest
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from docs_build import frontmatter  # noqa: E402

MARK = "<!-- generated by container_build.py from the folder tree and LEGACY.md; do not edit -->"
LEGACY = re.compile(r"^- (\S+) — (\S+) — (\d{4}-\d{2}-\d{2})\s*$")
SKIP = {"node_modules", "__pycache__", "docs"}  # docs = 컨테이너 자기 문서


def git(path, *args):
    r = subprocess.run(["git", "-C", str(path), *args], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def is_project(d):
    return (d / ".git").exists() or (d / "docs").is_dir()


def children(d):
    return [c for c in sorted(d.iterdir()) if c.is_dir() and not c.name.startswith((".", "_")) and c.name not in SKIP]


def is_container(d):
    return (d / "PROJECTS.md").is_file()


def cell(s):
    return s.replace("|", "\\|").replace("\n", " ").strip()


def description(d):
    for f in (d / "docs/documentation/overview.md", d / "README.md"):
        if f.is_file():
            _, body = frontmatter(f.read_text(encoding="utf-8", errors="ignore"))
            for line in body.splitlines():
                s = line.strip()
                if s and not s.startswith(("#", ">", "!", "[", "<", "|", "-", "`", "=")):
                    s = re.split(r"(?<=다\.)\s|(?<=\.)\s(?=[A-Z가-힣])", s)[0]  # 첫 문장
                    return s[:140] + ("…" if len(s) > 140 else "")
    return "—"


def stage(d):
    ov = d / "docs/documentation/overview.md"
    if ov.is_file() and frontmatter(ov.read_text(encoding="utf-8"))[0].get("kind") == "routine":
        return "v2", "루틴 (지금 = docs/current_status.md, 데이터 생성물)"
    if (d / "docs/state").is_dir():
        for p in sorted((d / "docs/state").glob("S*.md")):
            fm, _ = frontmatter(p.read_text(encoding="utf-8"))
            if fm.get("status") == "active":
                return "v2", f"{p.stem} {fm.get('title', '')}".strip()
        return "v2", "—"
    return ("v1" if (d / "docs/current_status.md").is_file() else "—"), "—"


def row(d, root):
    remote = re.sub(r"^https://github\.com/|\.git$", "", git(d, "remote", "get-url", "origin")) if (d / ".git").exists() else ""
    last = git(d, "log", "-1", "--format=%cs") if remote or (d / ".git").exists() else ""
    dirty = str(len(git(d, "status", "--porcelain").splitlines())) if (d / ".git").exists() else "—"
    fmt, st = stage(d)
    return f"| [{d.name}]({d.relative_to(root).as_posix()}/) | {cell(description(d))} | {remote or '—'} | {last or '—'} | {dirty} | {fmt} | {cell(st)} |"


def legacy(root):
    f, out, fails = root / "LEGACY.md", {}, []
    if f.is_file():
        for n, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
            if line.startswith("- "):
                m = LEGACY.match(line)
                if m:
                    out[m.group(1)] = (m.group(2), m.group(3))
                else:
                    fails.append(f"LEGACY.md:{n}: 형식은 `- <이름> — <remote> — <YYYY-MM-DD>`")
    return out, fails


def render(root):
    leg, fails = legacy(root)
    kids = children(root)
    containers = [c for c in kids if is_container(c) and c.name not in leg]  # 자기 docs/ 가 있어도 컨테이너
    projects = [c for c in kids if is_project(c) and c not in containers and c.name not in leg]
    others = [c.name for c in kids if c not in projects and c not in containers and c.name not in leg]
    head = "| 이름 | 설명 | remote | 마지막 커밋 | 미커밋 | docs | 현재 단계 |\n|---|---|---|---|---|---|---|"
    out = [MARK, f"# {root.name} — 프로젝트 목록", "", f"## 프로젝트 ({len(projects)})", "", head, *(row(c, root) for c in projects)]
    if containers:
        out += ["", f"## 컨테이너 ({len(containers)})", "", *(f"- [{c.name}]({c.name}/PROJECTS.md) — {cell(description(c))}" for c in containers)]
    if leg:
        out += ["", f"## 보관 ({len(leg)}) — LEGACY.md", "", "| 이름 | remote | 보관일 | 로컬 |", "|---|---|---|---|"]
        out += [f"| {n} | {r} | {d} | {'있음' if (root / n).is_dir() else '없음 (clone 으로 복구)'} |" for n, (r, d) in sorted(leg.items())]
    if others:
        out += ["", f"프로젝트가 아닌 폴더: {', '.join(others)}"]
    return "\n".join(out) + "\n", fails, containers


def run(root, check=False):
    root = Path(root).resolve()
    text, fails, containers = render(root)
    target = root / "PROJECTS.md"
    if check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            fails.append(f"{target}: 생성물이 최신이 아님 (container_build.py 실행 필요)")
    else:
        target.write_text(text, encoding="utf-8")
    for c in containers:
        fails += run(c, check)
    return fails


def selftest():
    env = ["-c", "user.name=t", "-c", "user.email=t@t", "-c", "init.defaultBranch=main"]
    with tempfile.TemporaryDirectory() as t:
        root = Path(t) / "box"
        a = root / "alpha"; (a / "docs/state").mkdir(parents=True); (a / "docs/documentation").mkdir()
        (a / "docs/state/S001.md").write_text("---\ntitle: 첫 단계\nstatus: done\n---\n", encoding="utf-8")
        (a / "docs/state/S002.md").write_text("---\ntitle: \"둘째: 진행\"\nstatus: active\n---\n", encoding="utf-8")
        (a / "docs/documentation/overview.md").write_text("---\ntitle: x\n---\n알파는 테스트 프로젝트다. 둘째 문장.\n", encoding="utf-8")
        subprocess.run(["git", *env, "init", "-q", str(a)], check=True)
        subprocess.run(["git", "-C", str(a), *env, "remote", "add", "origin", "https://github.com/u/alpha.git"], check=True)
        subprocess.run(["git", "-C", str(a), *env, "add", "."], check=True)
        subprocess.run(["git", "-C", str(a), *env, "commit", "-qm", "c"], check=True)
        (a / "dirty.txt").write_text("x")
        r = root / "rho" / "docs/documentation"; r.mkdir(parents=True)
        (r / "overview.md").write_text("---\ntitle: 루프\nkind: routine\nnow: tools/now.py\n---\n반복 루프다.\n", encoding="utf-8")
        b = root / "beta"; (b / "docs").mkdir(parents=True); (b / "docs/current_status.md").write_text("x")
        (b / "README.md").write_text("# Beta\n\nBeta does a | thing. More.\n")
        n = root / "nest" / "sub" / "inner"; (n / "docs").mkdir(parents=True); (root / "nest/docs").mkdir()  # 자기 docs 가 있고 프로젝트가 두 단계 아래
        (root / "nest/PROJECTS.md").write_text(""); (root / "nest/sub/PROJECTS.md").write_text("")  # 컨테이너 선언
        g = root / "gamma" / "bridge"; (g / "docs").mkdir(parents=True); (root / "gamma/docs").mkdir()  # 하위에 docs 가 있는 프로젝트
        (root / "plain").mkdir(); (root / "node_modules").mkdir(); (root / "old").mkdir()
        (root / "LEGACY.md").write_text("# 보관\n- old — u/old — 2026-09-29\n- gone — u/gone — 2026-09-01\n", encoding="utf-8")
        assert run(root) == [] and run(root, check=True) == [], "첫 빌드 후 check 통과"
        p = (root / "PROJECTS.md").read_text(encoding="utf-8")
        assert run(root) == [] and (root / "PROJECTS.md").read_text(encoding="utf-8") == p, "결정론"
        for want in ("| [alpha](alpha/) | 알파는 테스트 프로젝트다. | u/alpha |", "| 1 | v2 | S002 둘째: 진행 |",
                     "| [beta](beta/) | Beta does a \\| thing. | — | — | — | v1 | — |",
                     "- [nest](nest/PROJECTS.md)", "| gone | u/gone | 2026-09-01 | 없음 (clone 으로 복구) |",
                     "| old | u/old | 2026-09-29 | 있음 |", "| v2 | 루틴 (지금 = docs/current_status.md, 데이터 생성물) |", "프로젝트가 아닌 폴더: plain"):
            assert want in p, want
        assert "node_modules" not in p and "| [old]" not in p and "| [nest]" not in p, "SKIP·보관 폴더는 프로젝트 표에 없음"
        assert "- [sub](sub/PROJECTS.md)" in (root / "nest/PROJECTS.md").read_text(encoding="utf-8"), "중첩 컨테이너"
        assert "[inner](inner/)" in (root / "nest/sub/PROJECTS.md").read_text(encoding="utf-8"), "두 단계 아래 프로젝트"
        assert "| [gamma](gamma/)" in p and "[bridge]" not in p, "하위 docs 가 있어도 프로젝트"
        (b / "README.md").write_text("# Beta\n\nChanged.\n")
        assert any("최신이 아님" in f for f in run(root, check=True)), "stale 감지"
        (root / "LEGACY.md").write_text("- old u/old 2026\n", encoding="utf-8")
        assert any("LEGACY.md:1" in f for f in run(root)), "LEGACY 형식 오류"
    print("selftest OK — 결정론·stale·LEGACY 형식·중첩 컨테이너·설명 추출·단계·루틴·SKIP 발화")


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        selftest(); sys.exit(0)
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not args:
        sys.exit(__doc__)
    fails = run(args[0], check="--check" in sys.argv)
    for f in fails:
        print("FAIL", f)
    print(f"{len(fails)} FAIL"); sys.exit(1 if fails else 0)
